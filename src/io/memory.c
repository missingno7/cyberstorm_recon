#include <windows.h>
extern char errorMemory[];
extern "C" void AssertFail(const char *file, int line, const char *message);
 static char memorySourceFile[] = __FILE__;
unsigned long MemoryStatusValue(int useTotalVirtual)
{
    MEMORYSTATUS status;
    status.dwLength = sizeof(status);
    GlobalMemoryStatus(&status);
    if (useTotalVirtual)
        return status.dwTotalVirtual;
    return status.dwAvailPhys;
}

void *GlobalBlockFree(void *block)
{
    return GlobalFree(block);
}

void *GlobalBlockAlloc(unsigned long bytes, unsigned int options)
{
    void *block = 0;
    if (bytes != 0) {
        if (options & 1)
            block = (void *)0x40;
        block = GlobalAlloc((unsigned int)block, bytes);
    }
    if (block == 0 && (options & 4)) {






























































































































































































































































































        AssertFail(memorySourceFile, __LINE__, errorMemory);
    }
    return block;
}

